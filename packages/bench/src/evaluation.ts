import type { MutationResult, MutationSummary } from "./evaluate.ts";
import type { CorpusRun, PerfResults } from "./perf.ts";

export interface MutationResults {
  kind: "drift-mutations/v1";
  engineVersion: string;
  generatedAt: string;
  seeds: number[];
  specs: string[];
  summary: MutationSummary;
  results: MutationResult[];
  skipped: string[];
}

const n = (value: number) => value.toLocaleString("en-GB");
const pct = (value: number | null) => (value === null ? "n/a" : `${(value * 100).toFixed(1)}%`);
const s = (ms: number) => (ms >= 10_000 ? `${(ms / 1000).toFixed(1)} s` : `${String(ms)} ms`);

function linearity(runs: readonly CorpusRun[]): string {
  const first = runs[0];
  const last = runs.at(-1);
  if (!first || !last || first === last) return "";
  const perLine = (run: CorpusRun) => run.ms / run.lines;
  const ratio = perLine(last) / perLine(first);
  return `Time per line changes by a factor of ${ratio.toFixed(2)} from ${n(first.lines)} to ${n(last.lines)} lines (1.00 would be exactly linear; below 1 is better than linear).`;
}

/**
 * Renders docs/EVALUATION.md from the committed result files only, so the page can be regenerated and checked
 * in CI without re-running any benchmark. Every number on the page comes from a result file.
 */
export function renderEvaluation(perf: PerfResults | undefined, mutations: MutationResults | undefined): string {
  let md = `# Evaluation\n\n<!-- Generated by \`pnpm --filter @drift/bench run evaluation\` from docs/evaluation/*.json. Do not edit by hand; CI checks it. -->\n\n`;
  md +=
    "Every number on this page comes from `packages/bench` output (CLAUDE.md). Re-run the benchmarks with `pnpm --filter @drift/bench run all` and commit the changed files in `docs/evaluation/`.\n";

  md += "\n## Performance\n\n";
  if (!perf) {
    md += "Not measured yet.\n";
  } else {
    const env = perf.environment;
    md += `Measured on ${perf.generatedAt.slice(0, 10)} with engine ${perf.engineVersion}: ${env.cpu} (${String(env.cores)} cores), ${String(env.memoryGiB)} GiB RAM, ${env.platform}, Node ${env.node}. Memory is the process's peak resident set size, sampled every ${String(perf.config.sampleIntervalMs)} ms.\n`;

    md += `\n### Recorded traffic of growing size\n\n\`drift compare\` on \`${perf.corpus.spec}\` → \`${perf.corpus.head}\`, streaming a generated drift-traffic/v1 file. Memory ceiling fixed in the bench config: **${String(perf.config.memoryCeilingMiB)} MiB**.\n\n`;
    md +=
      "| Lines | File | Time | Lines/s | Kept samples | Peak RSS | Within ceiling |\n| ---: | ---: | ---: | ---: | ---: | ---: | :---: |\n";
    for (const run of perf.corpus.runs) {
      md += `| ${n(run.lines)} | ${String(run.fileMiB)} MiB | ${s(run.ms)} | ${n(run.linesPerSecond)} | ${n(run.kept)} | ${String(run.peakRssMiB)} MiB | ${run.withinCeiling ? "yes" : "**no**"} |\n`;
    }
    const scaling = linearity(perf.corpus.runs);
    if (scaling) md += `\n${scaling}\n`;

    md += `\n### Cached re-run\n\nThe same comparison (${n(perf.cache.lines)} lines of traffic) twice with a stage cache: **${s(perf.cache.cold.ms)}** the first time, **${s(perf.cache.warm.ms)}** when Diff, Corpus, Verify and Classify are reused.\n`;

    md += "\n### Real-world specs\n\n";
    if (perf.fixtures.length === 0) {
      md += `Not measured: ${perf.fixturesSkipped ?? "no fixtures"}.\n`;
    } else {
      md +=
        "| Spec | Operations | Ingest | Compare with itself | Changes | Compare with a mutant | Changes (BREAKING) | Peak RSS |\n| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |\n";
      for (const f of perf.fixtures) {
        const peak = Math.max(f.ingest.peakRssMiB, f.selfCompare.peakRssMiB, f.mutatedCompare.peakRssMiB);
        md += `| ${f.id} | ${n(f.operations)} | ${s(f.ingest.ms)} | ${s(f.selfCompare.ms)} | ${String(f.selfCompare.changes)} | ${s(f.mutatedCompare.ms)} | ${String(f.mutatedCompare.changes)} (${String(f.mutatedCompare.breaking)}) | ${String(peak)} MiB |\n`;
      }
      const [first] = perf.fixtures;
      if (first)
        md += `\nThe mutant adds a required request property (${first.mutatedCompare.mutation} for ${first.id}); the comparison includes synthetic evidence for every affected operation.\n`;
    }
  }

  md += "\n## Accuracy on labelled mutations (DRIFT only)\n\n";
  if (!mutations) {
    md += "Not measured yet.\n";
  } else {
    const sum = mutations.summary;
    md += `Each mutation changes one place in a spec and is labelled breaking or safe by the operator that made it (\`packages/bench/src/mutations.ts\`). DRIFT compares the original with the mutant **without traffic**, so its evidence is synthetic. Specs: ${mutations.specs.map((spec) => `\`${spec}\``).join(", ")}; seeds ${mutations.seeds.join(", ")}. The comparison with oasdiff arrives in M8.\n\n`;
    md +=
      "| Mutations | Total | DRIFT: BREAKING | DRIFT: RISKY | DRIFT: SAFE or nothing |\n| --- | ---: | ---: | ---: | ---: |\n";
    md += `| Breaking | ${String(sum.breaking.total)} | ${String(sum.breaking.proven)} (proven) | ${String(sum.breaking.flagged)} (flagged, unproven) | ${String(sum.breaking.missed)} (missed) |\n`;
    md += `| Safe | ${String(sum.safe.total)} | ${String(sum.safe.falseBreaking)} (false BREAKING) | ${String(sum.safe.flagged)} (over-cautious) | ${String(sum.safe.clean)} (correct) |\n`;
    md += `\nBREAKING precision **${pct(sum.precision)}**, recall **${pct(sum.recall)}**.\n\n`;
    md +=
      "<details><summary>Every mutation</summary>\n\n| Spec | Operator | Label | DRIFT | Mutation |\n| --- | --- | --- | --- | --- |\n";
    for (const r of mutations.results) {
      md += `| ${r.spec} | ${r.operator} | ${r.label} | ${r.verdict} | ${r.description.replace(/\|/g, "\\|")} |\n`;
    }
    md += "\n</details>\n";
    if (mutations.skipped.length > 0) md += `\nOperators with no suitable place: ${mutations.skipped.join("; ")}.\n`;
  }
  return md;
}
